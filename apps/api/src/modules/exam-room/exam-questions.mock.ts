/**
 * انتخاب هوشمند مجموعه سوالات آزمون بر اساس اسلاگ یا دسته‌بندی
 */
export function getQuestionsForExam(identifier: string): ExamQuestion[] {
  const lower = (identifier || '').toLowerCase();

  if (lower.includes('offline-resilience') || lower.includes('1min')) {
    return OFFLINE_RESILIENCE_1MIN_QUESTIONS;
  }

  if (lower.includes('stage-1') || lower.includes('stage1')) {
    return STAGE1_PILOT_QUESTIONS;
  }

  if (lower.includes('stage-2') || lower.includes('stage2') || lower.includes('genetics')) {
    return STAGE2_PILOT_QUESTIONS;
  }

  return CAMPBELL_PILOT_QUESTIONS;
}
